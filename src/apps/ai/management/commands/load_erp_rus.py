class Command(BaseCommand):
    help = "Load Russian ERP FAQ knowledge documents into KnowledgeDocument"

    def handle(self, *args, **options):
        created = 0
        updated = 0

        for item in DOCUMENTS:
            _, is_created = KnowledgeDocument.objects.update_or_create(
                source_key=item["source_key"],
                defaults={
                    "title": item["title"],
                    "source_type": item["source_type"],
                    "content": item["content"].strip(),
                    "metadata": item.get("metadata", {}),
                    "is_active": True,
                },
            )

            if is_created:
                created += 1
            else:
                updated += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Russian FAQ knowledge loaded successfully. Created: {created}, Updated: {updated}"
            )
        )